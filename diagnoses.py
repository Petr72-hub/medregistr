def therapy_diagnosis(passport_diagnosis):
    """Keep the exact passport label; classify K50/K51 including subcategories."""
    text = str(passport_diagnosis or '').strip()
    match = re.match(r'^([A-Z]\d{2})(?:\.\d+)?(?=\s|$|[—–-])', text.upper())
    code = match.group(1) if match else None
    if code == 'K50':
        return text, 'Crohn'
    if code == 'K51':
        return text, 'UC'
    return text or 'Диагноз не указан в паспортной части', text or 'unspecified'
